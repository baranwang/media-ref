// buf plugin: turns the comments in proto/mediaref/v1 into a lookup table keyed by full proto name
// ("mediaref.v1.MediaService.GetMedia", "mediaref.v1.GetMediaRequest.ref", ...). protoc-gen-es
// strips comments from the runtime descriptors, so the MCP server reads its descriptions from here.
import type { AnyDesc } from "@bufbuild/protobuf";
import { nestedTypes } from "@bufbuild/protobuf/reflect";
import { createEcmaScriptPlugin, getComments, runNodeJs } from "@bufbuild/protoplugin";

const PUBLIC_PACKAGE = "mediaref.v1";

function comment(desc: Exclude<AnyDesc, { kind: "file" }>): string | undefined {
  const { leading, trailing } = getComments(desc);
  const text = (leading ?? trailing)?.trim().replace(/\s*\n\s*/g, " ");
  return text || undefined;
}

runNodeJs(
  createEcmaScriptPlugin({
    name: "protoc-gen-proto-docs",
    version: "v1",
    generateTs(schema) {
      const docs: [string, string][] = [];
      const add = (name: string, desc: Exclude<AnyDesc, { kind: "file" }>) => {
        const text = comment(desc);
        if (text) docs.push([name, text]);
      };
      for (const file of schema.files) {
        if (file.proto.package !== PUBLIC_PACKAGE) continue;
        for (const type of nestedTypes(file)) {
          if (type.kind === "extension") continue;
          add(type.typeName, type);
          const members =
            type.kind === "service"
              ? type.methods
              : type.kind === "message"
                ? type.fields
                : type.kind === "enum"
                  ? type.values
                  : [];
          for (const member of members) add(`${type.typeName}.${member.name}`, member);
        }
      }
      const f = schema.generateFile("proto-docs.ts");
      f.print(
        "// Generated by scripts/protoc-gen-proto-docs.ts from the comments in proto/mediaref/v1.",
      );
      f.print("export const PROTO_DOCS: Readonly<Record<string, string>> = {");
      for (const [name, text] of docs.sort(([a], [b]) => a.localeCompare(b))) {
        f.print(`  ${JSON.stringify(name)}: ${JSON.stringify(text)},`);
      }
      f.print("};");
    },
  }),
);
